function translateText(value) {
    const trimmed = value.trim()
    let translated = am[trimmed]
    if (!translated) {
        const dynamic = [
            [/^Stays in (.+)$/, (_, city) => `በ${city} ያሉ መኖሪያዎች`],
            [/^(\d+) properties available$/, (_, count) => `${count} መኖሪያ ቤቶች ክፍት ናቸው`],
            [/^(\d+) property available$/, (_, count) => `${count} መኖሪያ ቤት ክፍት ነው`],
            [/^No (upcoming|current|completed|cancelled) bookings$/, (_, status) => `${am[status[0].toUpperCase() + status.slice(1)] || status} ቦታ ማስያዣ የለም`],
            [/^(\d+) nights?$/, (_, count) => `${count} ሌሊቶች`],
            [/^(\d+) guests?$/, (_, count) => `${count} እንግዶች`],
        ]
        for (const [pattern, render] of dynamic) {
            const match = trimmed.match(pattern)
            if (match) { translated = render(...match); break }
        }
    }
    if (!translated) return value
    const start = value.indexOf(trimmed)
    return `${value.slice(0, start)}${translated}${value.slice(start + trimmed.length)}`
}

const en = Object.fromEntries(Object.entries(am).map(([english, amharic]) => [amharic, english]))
function restoreText(value) {
    const trimmed = value.trim()
    const restored = en[trimmed]
    if (!restored) return value
    const start = value.indexOf(trimmed)
    return `${value.slice(0, start)}${restored}${value.slice(start + trimmed.length)}`
}

export default function LanguageLayer() {
    const language = useLanguageStore((state) => state.language)
    const role = useUserStore((state) => state.role)

    useEffect(() => {
        const useAmharic = language === 'am' && role !== 'ADMIN'
        const root = document.documentElement
        const body = document.body
        root.lang = useAmharic ? 'am' : 'en'
        body.classList.toggle('amharic-ui', useAmharic)
        const translateNode = (node, transform) => {
            if (node.nodeType === Node.TEXT_NODE && node.nodeValue) {
                const transformed = transform(node.nodeValue)
                if (transformed !== node.nodeValue) node.nodeValue = transformed
                return
            }
            if (node.nodeType !== Node.ELEMENT_NODE) return
            for (const attribute of ['placeholder', 'aria-label', 'title']) {
                const value = node.getAttribute(attribute)
                if (value) {
                    const translated = transform(value)
                    if (translated !== value) node.setAttribute(attribute, translated)
                }
            }
            node.childNodes.forEach((child) => translateNode(child, transform))
        }
        const transform = useAmharic ? translateText : restoreText
        translateNode(body, transform)
        if (!useAmharic) return undefined
        const observer = new MutationObserver((mutations) => {
            for (const mutation of mutations) {
                if (mutation.type === 'characterData') translateNode(mutation.target, translateText)
                else mutation.addedNodes.forEach((node) => translateNode(node, translateText))
                if (mutation.type === 'attributes') translateNode(mutation.target, translateText)
            }
        })
        observer.observe(body, { subtree: true, childList: true, characterData: true, attributes: true, attributeFilter: ['placeholder', 'aria-label', 'title'] })
        return () => observer.disconnect()
    }, [language, role])

    return null
}
